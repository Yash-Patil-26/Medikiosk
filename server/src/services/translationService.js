/**
 * Fast translation using hardcoded dictionaries
 * No external API dependency for production stability
 */
export function translateText(text, targetLang) {
  if (!text || !targetLang || targetLang === 'en') {
    return text;
  }

  const langTranslations = TRANSLATIONS[targetLang];
  if (!langTranslations) {
    return text;
  }

  return langTranslations[text] || text;
}
